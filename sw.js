/* =========================================================
   QUIZ ARENA SERVICE WORKER  (the ONLY service worker)

   Why there is one and not two: a scope ("/") can only have one
   active service worker. The old setup registered sw.js from
   main.js and firebase-messaging-sw.js from pushNotifications.js,
   both at "/", so whichever registered last silently evicted the
   other. Caching and push now live together here;
   firebase-messaging-sw.js is a one-line shim that imports this file.

   What it does
   1. PRECACHE   -- on install, downloads the app shell (index.html,
                    every css/js file, icons) plus the Firebase SDK
                    modules the app imports from gstatic.com, so the
                    app boots with no network at all. Progress is
                    broadcast to the page (welcome screen status line).
   2. RUNTIME    -- navigations: network first, but if the network takes
                    more than 3.5s (bad "lie-fi" data) the cached shell
                    is served instead. Same-origin assets: stale-while-
                    revalidate. Firebase SDK: cache first.
   3. PUSH       -- FCM background notifications (moved from
                    firebase-messaging-sw.js, same behaviour).

   Everything else (Firestore, Auth, Cloud Functions, Flutterwave,
   Cloudinary) is deliberately NOT touched -- those go straight to the
   network. Firestore has its own offline cache (js/firebase/config.js).

   The block between the precache-manifest markers is generated by
   `node tools/build-sw.mjs` -- run it before every deploy so a new
   release gets a new cache version.
========================================================= */
