/* ---------------------------------------------------------
   PRECACHE
--------------------------------------------------------- */
let progress = { done: 0, total: 0, failed: 0, ready: false };
let precacheRun = null;

async function broadcast() {
  const msg = { type: "qa-precache", version: PRECACHE_VERSION, ...progress };
  const all = await self.clients.matchAll({ includeUncontrolled: true });
  all.forEach((c) => c.postMessage(msg));
}

/** A redirected response can't answer a navigation, so rebuild it clean. */
async function cleanResponse(res) {
  if (!res.redirected) return res;
  return new Response(await res.blob(), {
    status: res.status,
    statusText: res.statusText,
    headers: res.headers,
  });
}

/**
 * Runs `worker` over `queue` with limited concurrency. The queue is
 * consumed in place, so a worker may push new items onto it (the
 * Firebase crawl below relies on that).
 */
async function runPool(queue, worker) {
  const runners = Array.from({ length: CONCURRENCY }, async () => {
    while (queue.length) await worker(queue.shift());
  });
  await Promise.all(runners);
}

async function precacheShell(cache) {
  await runPool(PRECACHE_URLS.slice(), async (url) => {
    try {
      if (!(await cache.match(url))) {
        // cache:"reload" skips the HTTP cache so a new release never
        // caches yesterday's file from the browser's own cache.
        const res = await fetch(new Request(url, { cache: "reload" }));
        if (!res.ok) throw new Error(res.status);
        await cache.put(url, await cleanResponse(res));
      }
      progress.done++;
    } catch (e) {
      progress.failed++;
    }
    await broadcast();
  });
}

/** Pull `from "..."` / `import "..."` / `import("...")` specifiers out of a module. */
function findImports(source) {
  const found = new Set();
  const re = /(?:\bfrom\s*|\bimport\s*\(?\s*)["']([^"']+)["']/g;
  let m;
  while ((m = re.exec(source))) found.add(m[1]);
  return [...found];
}

async function precacheFirebaseSdk() {
  const cdn = await caches.open(CDN_CACHE);
  const queue = PRECACHE_CDN.slice();
  const seen = new Set(queue);
  progress.total += queue.length;

  // The SDK files import each other, so walk the import graph.
  await runPool(queue, async (url) => {
    try {
      let res = await cdn.match(url);
      if (!res) {
        const fetched = await fetch(url, { mode: "cors", credentials: "omit" });
        if (!fetched.ok) throw new Error(fetched.status);
        await cdn.put(url, fetched.clone());
        res = fetched;
      }
      const text = await res.clone().text();
      for (const spec of findImports(text)) {
        let next;
        try {
          next = new URL(spec, url);
        } catch {
          continue;
        }
        if (next.hostname !== "www.gstatic.com" || !next.pathname.startsWith("/firebasejs/")) continue;
        if (seen.has(next.href)) continue;
        seen.add(next.href);
        progress.total++;
        queue.push(next.href);
      }
      progress.done++;
    } catch (e) {
      progress.failed++;
    }
    await broadcast();
  });
}

function precacheAll() {
  if (precacheRun) return precacheRun;
  precacheRun = (async () => {
    progress = { done: 0, total: PRECACHE_URLS.length, failed: 0, ready: false };
    await broadcast();

    const shell = await caches.open(SHELL_CACHE);
    await precacheShell(shell);
    await precacheFirebaseSdk();

    progress.ready = progress.failed === 0;
    await shell.put(
      META_KEY,
      new Response(JSON.stringify({ version: PRECACHE_VERSION, ...progress, at: Date.now() }), {
        headers: { "Content-Type": "application/json" },
      }),
    );
    await broadcast();
  })().finally(() => {
    precacheRun = null;
  });
  return precacheRun;
}

self.addEventListener("install", (event) => {
  self.skipWaiting();
  // Never reject: an install that fails on a weak network would leave the
  // site with no service worker at all (and no install prompt). Missing
  // files are topped up on activate / next start instead.
  event.waitUntil(precacheAll().catch((e) => console.warn("[sw] precache:", e)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((n) => n.startsWith("qa-shell-") && n !== SHELL_CACHE)
          .map((n) => caches.delete(n)),
      );
      await self.clients.claim();
      // Top up anything the install couldn't fetch (fast no-op when complete).
      precacheAll().catch(() => {});
    })(),
  );
});

self.addEventListener("message", (event) => {
  const data = event.data || {};
  if (data.type === "SKIP_WAITING") self.skipWaiting();
  if (data.type === "PRECACHE_RETRY") event.waitUntil(precacheAll().catch(() => {}));
});

